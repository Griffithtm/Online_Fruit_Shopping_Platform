package dao;

import java.sql.Connection;
import java.sql.SQLException;
import java.util.List;
import model.CountResult;
import model.Notification;


public class NotificationDAO {

    private static final String COLUMNS =
            "id, user_id, event_type, title, content, link_url, " +
            "send_email, email_status, email_retry_count, read_at, created_at, " +
            "email_provider_ref, next_retry_at, dedup_key";

    private static final int MAX_BATCH_SIZE = 100;

    /**
     * Create an in-app notification. If sendEmail is true, queue an email too.
     * Returns the new ID generated by SQL Server's IDENTITY column.
     *
     * The unique index on dedup_key prevents duplicate event notifications.
     * This method does not catch duplicate-key errors (2601/2627); the Service
     * can resolve these using findByDedupKey().
     * @param c
     * @param userId
     * @param eventType
     * @return 
     */
    public long create(Connection c, long userId, String eventType,
                       String title, String content, String linkUrl,
                       boolean sendEmail, String dedupKey) throws SQLException {
        String sql = "INSERT INTO dbo.notifications " +
                "(user_id, event_type, title, content, link_url, " +
                "send_email, email_status, dedup_key) " +
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

        return Database.insert(c, sql, userId, eventType, title, content,
                linkUrl, sendEmail, sendEmail ? "QUEUED" : null, dedupKey);
    }

    public Notification findById(Connection c, long notificationId,
                                 long userId) throws SQLException {
        return Database.one(Notification.class, c,
                "SELECT " + COLUMNS + " FROM dbo.notifications " +
                "WHERE id = ? AND user_id = ?", notificationId, userId);
    }

    public Notification findByDedupKey(Connection c, String dedupKey)
            throws SQLException {
        if (dedupKey == null || dedupKey.isBlank()) return null;
        return Database.one(Notification.class, c,
                "SELECT " + COLUMNS + " FROM dbo.notifications " +
                "WHERE dedup_key = ?", dedupKey);
    }


    public List<Notification> findByUser(Connection c, long userId,
                                          int page, int pageSize) throws SQLException {
        if (page < 0) throw new IllegalArgumentException("page must be >= 0");
        checkLimit(pageSize);
        long offset = (long) page * pageSize;
        return Database.rows(Notification.class, c,
                "SELECT " + COLUMNS + " FROM dbo.notifications " +
                "WHERE user_id = ? " +
                "ORDER BY created_at DESC, id DESC " +
                "OFFSET ? ROWS FETCH NEXT ? ROWS ONLY",
                userId, offset, pageSize);
    }

    public List<Notification> findUnread(Connection c, long userId, int limit)
            throws SQLException {
        checkLimit(limit);
        return Database.rows(Notification.class, c,
                "SELECT TOP (?) " + COLUMNS + " FROM dbo.notifications " +
                "WHERE user_id = ? AND read_at IS NULL " +
                "ORDER BY created_at DESC, id DESC",
                limit, userId);
    }

    /**
     * Optional: retrieve newly created messages after lastKnownId.
     * Useful for incremental AJAX polling without reloading the entire inbox.
     * Returns oldest first so the frontend can append in the correct order.
     */
    public List<Notification> findAfterId(Connection c, long userId,
                                           long lastKnownId, int limit)
            throws SQLException {
        if (lastKnownId < 0) {
            throw new IllegalArgumentException("lastKnownId must be >= 0");
        }
        checkLimit(limit);
        return Database.rows(Notification.class, c,
                "SELECT TOP (?) " + COLUMNS + " FROM dbo.notifications " +
                "WHERE user_id = ? AND id > ? ORDER BY id ASC",
                limit, userId, lastKnownId);
    }

    public long countUnread(Connection c, long userId) throws SQLException {
        CountResult result = Database.one(CountResult.class, c,
                "SELECT COUNT_BIG(*) AS n FROM dbo.notifications " +
                "WHERE user_id = ? AND read_at IS NULL", userId);
        return result == null ? 0L : result.getN();
    }

    public int markAsRead(Connection c, long notificationId, long userId)
            throws SQLException {
        return Database.update(c,
                "UPDATE dbo.notifications SET read_at = SYSUTCDATETIME() " +
                "WHERE id = ? AND user_id = ? AND read_at IS NULL",
                notificationId, userId);
    }

    public int markAllAsRead(Connection c, long userId) throws SQLException {
        return Database.update(c,
                "UPDATE dbo.notifications SET read_at = SYSUTCDATETIME() " +
                "WHERE user_id = ? AND read_at IS NULL", userId);
    }


    public List<Notification> findDueEmails(Connection c, int limit)
            throws SQLException {
        checkLimit(limit);
        return Database.rows(Notification.class, c,
                "SELECT TOP (?) " + COLUMNS + " FROM dbo.notifications " +
                "WHERE send_email = 1 AND email_status = 'QUEUED' " +
                "AND email_retry_count <= 5 " +
                "AND (next_retry_at IS NULL " +
                "OR next_retry_at <= SYSUTCDATETIME()) " +
                "ORDER BY created_at ASC, id ASC", limit);
    }
    public int markEmailSent(Connection c, long notificationId,
                             String providerReference) throws SQLException {
        return Database.update(c,
                "UPDATE dbo.notifications " +
                "SET email_status = 'SENT', email_provider_ref = ?, " +
                "next_retry_at = NULL " +
                "WHERE id = ? AND send_email = 1 AND email_status = 'QUEUED'",
                providerReference, notificationId);
    }

    public int scheduleEmailRetry(Connection c, long notificationId)
            throws SQLException {
        return Database.update(c,
                "UPDATE dbo.notifications SET " +
                "email_retry_count = email_retry_count + 1, " +
                "email_status = CASE WHEN email_retry_count >= 5 " +
                "THEN 'FAILED' ELSE 'QUEUED' END, " +
                "next_retry_at = CASE WHEN email_retry_count >= 5 " +
                "THEN NULL ELSE DATEADD(MINUTE, 5, SYSUTCDATETIME()) END " +
                "WHERE id = ? AND send_email = 1 " +
                "AND email_status = 'QUEUED' AND email_retry_count <= 5",
                notificationId);
    }

    public int markEmailDelivered(Connection c, long notificationId)
            throws SQLException {
        return Database.update(c,
                "UPDATE dbo.notifications SET email_status = 'DELIVERED' " +
                "WHERE id = ? AND email_status = 'SENT'", notificationId);
    }

    public int markEmailBounced(Connection c, long notificationId)
            throws SQLException {
        return Database.update(c,
                "UPDATE dbo.notifications SET email_status = 'BOUNCED' " +
                "WHERE id = ? AND email_status = 'SENT'", notificationId);
    }

    private static void checkLimit(int limit) {
        if (limit < 1 || limit > MAX_BATCH_SIZE) {
            throw new IllegalArgumentException("limit must be between 1 and " + MAX_BATCH_SIZE);
        }
    }
}
